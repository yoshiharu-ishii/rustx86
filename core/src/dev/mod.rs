//! 装置。**「なにか」と「どう見つかるか」を分ける**
//! ([ADR-0018](../../../docs/adr/0018-devices-chip-card-bus.md))。
//!
//! - [`chip`] — **素子**。チップそのもので、番地もバスも知らない。
//!   機械を組まずに単体で試せる
//! - [`card`] — **基板**。素子 + 基板の都合 (PROMの並べ方・設定空間の名乗り)。
//!   同じ素子に別の基板を着せたのが NE2000 (ISA) と RTL8029 (PCI) である
//!
//! ## 新しい装置をどこに置くか
//!
//! 1. **素子は [`chip`]**。1素子1ファイル。バスや番地の話を持ち込まない
//! 2. **基板は [`card`]**。実機で言えば「その素子を載せた製品」で、持ち物は
//!    PROMの焼き方・窓の幅・バスへの名乗りといった**組み立ての都合**だけ
//! 3. **同じ素子が別のバスに出ている**なら、実体は [`chip`] に1つだけ置いて
//!    [`card`] を2枚作る。**二重実装しない** — 意味論の原本を1つに保つのは
//!    このリポジトリの原則で、ここでは実機の歴史 (RTL8029はNE2000互換を
//!    売りにした廉価チップ) とも一致する
//!
//! 再エクスポートしているのは、使う側 (バスのデコーダ) にとって素子がどの
//! ディレクトリに居るかは関係が無いからである。

pub mod card;
pub mod chip;

pub use card::virtio_blk::VirtioBlk;
