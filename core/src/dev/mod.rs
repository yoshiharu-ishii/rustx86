//! 装置。**ハードウェアバスごとにディレクトリ、装置ごとにファイル**
//! ([ADR-0017](../../../docs/adr/0017-network-isa-first.md))。
//!
//! - [`isa`] — ISA (とその前身のPC/XTバス) の装置。アドレスは定数で、
//!   デコーダは `match` で足りる
//! - [`pci`] — 装置を数える仕組み (設定空間) を持つ側。**番地はBARで動く**ので、
//!   振り分けも定数の`match`ではなくPCI側が実行時に持つ
//!
//! ## 新しい装置をどこに置くか
//!
//! 1. **その装置はどう見つけられるか**で決める。番地が定数なら `isa/`、
//!    設定空間から数えられるなら `pci/`。1装置1ファイル
//! 2. **同じチップが両方のバスに出ている**なら、実体は生まれた側に1つだけ
//!    置き、もう一方は皮 (設定空間の顔) だけを持つ。NE2000/RTL8029 がこれで、
//!    実体は [`isa::ne2000`]、PCIの顔は [`pci::rtl8029`] にある。
//!    **二重実装しない** — 意味論の原本を1つに保つのはこのリポジトリの原則で、
//!    ここでは実機の歴史 (RTL8029はNE2000互換を売りにした廉価チップ) とも一致する
//!
//! 再エクスポートしているのは、使う側 (バスのデコーダ) にとって装置の所属バスが
//! 型名の一部である必要は無いからである。

pub mod isa;
pub mod pci;

pub use isa::{Cmos, Crtc, Kbd8042, Ne2000, Pic8259, Pit8254, Uart16550};
