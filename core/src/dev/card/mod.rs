//! 基板 — **素子 + 基板の都合**。
//!
//! カードは素子だけでは動かない。MACを焼いたPROMがどう並ぶか、どの窓から
//! 覗かれるか、バスにどう名乗るか — この「基板の都合」を持つのがここである。
//!
//! - [`ne2000`] NE2000 (ISA) = [`Dp8390`](super::chip::Dp8390) + 倍幅PROM + 0x300の窓
//! - [`rtl8029`] RTL8029AS (PCI) = 同じ素子 + 平坦PROM + BARの窓 + 10EC:8029 の名乗り
//!
//! **どちらも素子は同じ1つ**である。実装を2つ持たないのはこのリポジトリの原則
//! (意味論の原本は1つ) だが、ここでは歴史の方が先にそう作っている — 実物の
//! RTL8029ASは「NE2000互換であること」を売りにした廉価チップで、Linuxのドライバも
//! ISA版とコアの `lib8390.c` を共有している。**皮だけ替わるのが正しい姿**で、
//! 中身まで写すとエミュレータの方が実機より複雑になる。
//!
//! ## なぜ「型」ではなく「組み立て」なのか
//!
//! 今の基板の都合は**すべて組み立て時に決まる**もの (PROMの並び・設定空間の名乗り)
//! なので、カードは素子を1枚組み上げて返す関数で足りる。走行中に基板側の振る舞いが
//! 要る装置 (拡張レジスタを持つカードなど) が来たら、そのときに型にする。
//! **無い振る舞いのために器だけ先に作らない。**

