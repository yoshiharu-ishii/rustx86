//! コードページ437 — **IBM PC の文字集合**。
//!
//! テキストVRAMの1バイトが、どの絵になるかを決める表である。
//! 0x20〜0x7E はASCIIと同じだが、**残り半分がPCらしさそのもの**になっている。
//!
//! - `0x00-0x1F` — ASCIIでは制御文字だが、テキストモードでは**絵として表示される**。
//!   ♥ ♦ ♣ ♠ や ♪ が入っているのは、当時のPCに絵を出す手段が他に無かったからで、
//!   ゲームのキャラクタにそのまま使われた
//! - `0xB0-0xDF` — 罫線と網掛けとブロック。**DOSの画面はこれで作られている**。
//!   ウィンドウの枠も、進捗バーも、ロゴも、全部この範囲の文字を並べたものである
//! - `0x80-0xAF`, `0xE0-0xFF` — 西欧の文字とギリシャ文字と数学記号
//!
//! FreeDOS のウェルカム画面が `0xDB` (█) の羅列で描かれていて、
//! ASCIIだけを拾う確認用の関数がそれを捨てていたため、**画面が空に見えた**。
//! 表を持たないと「出ているのに見えない」が起きる。
//!
//! 実際の字形はここでは持たない。Unicodeへ写して、描くのは
//! ブラウザのフォントに任せる (CLIの確認表示も同じ表を通す)。

